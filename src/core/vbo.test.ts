describe("parseClockSeconds", () => {
  it("reads HHMMSS.ss", () => {
    expect(parseClockSeconds("031747.00")).toBeCloseTo(3 * 3600 + 17 * 60 + 47, 5);
    expect(parseClockSeconds("031748.15")).toBeCloseTo(3 * 3600 + 17 * 60 + 48.15, 5);
  });
});

describe("parseVbo", () => {
  it("reads channels, the gate, and a midnight rollover", () => {
    const session = parseVbo(sampleVbo);
    expect(session.venue).toBe("Fontenay Le Comte");
    expect(session.startedAt).toBe("04/09/2026 03:17");
    expect(session.serial).toBe("123");
    expect(session.samples).toHaveLength(4);
    expect(session.samples[0].elapsed).toBe(0);
    expect(session.samples[1].elapsed).toBeCloseTo(0.04, 5);
    expect(session.samples[0].lat).toBeCloseTo(latitudeDegrees(2786.29538), 8);
    expect(session.samples[0].lon).toBeCloseTo(longitudeDegrees(47.39963), 8);
    expect(session.samples[0].lon).toBeLessThan(0);
    expect(session.samples[0].speed).toBeCloseTo(5.267, 3);
    expect(session.samples[0].latAcc).toBeCloseTo(-0.001, 4);
    expect(session.samples[0].sats).toBe(15);
    expect(session.samples[3].elapsed).toBeCloseTo(
      24 * 3600 - (3 * 3600 + 17 * 60 + 47) + 0.1,
      2,
    );
    expect(session.gate).not.toBeNull();
    expect(session.gate?.a.lat).toBeCloseTo(latitudeDegrees(2786.28551), 8);
    expect(session.gate?.a.lon).toBeCloseTo(longitudeDegrees(47.55339), 8);
    expect(session.gate?.b.lon).toBeLessThan(0);
  });
});

const describeFontenay = existsSync(fontenayPath) ? describe : describe.skip;

describeFontenay("Fontenay session", () => {
  const session = parseVbo(readFileSync(fontenayPath, "utf8"));

  it("lands on Circuits de Vendée", () => {
    const lats = session.samples.map((sample) => sample.lat);
    const lons = session.samples.map((sample) => sample.lon);
    const track = { lat: 46.438275, lon: -0.790039 };
    expect(Math.min(...lats)).toBeLessThan(track.lat);
    expect(Math.max(...lats)).toBeGreaterThan(track.lat);
    expect(Math.min(...lons)).toBeLessThan(track.lon);
    expect(Math.max(...lons)).toBeGreaterThan(track.lon);
    expect(session.venue).toContain("Fontenay");
    expect(session.samples.length).toBeGreaterThan(10_000);
  });

  it("finds full laps from the start finish gate", () => {
    expect(session.gate).not.toBeNull();
    const laps = detectLaps(session.samples, session.gate!);
    expect(laps).toHaveLength(5);
    const best = Math.min(...laps.map((lap) => lap.lapTime));
    expect(best).toBeCloseTo(65.68, 1);
    for (const lap of laps) {
      expect(lap.lapTime).toBeGreaterThan(60);
      expect(lap.lapTime).toBeLessThan(120);
      expect(lap.length).toBeGreaterThan(2100);
      expect(lap.length).toBeLessThan(2500);
      expect(lap.dist[0]).toBe(0);
      expect(lap.dist[lap.dist.length - 1]).toBeCloseTo(lap.length, 3);
      expect(lap.time[lap.time.length - 1]).toBeCloseTo(lap.lapTime, 3);
    }
  });
});
